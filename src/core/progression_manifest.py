def _base_node(
    node_id: str,
    kind: str,
    identifier: str,
    lane: str,
    position: tuple[float, int],
    prerequisites: tuple[str, ...] = (),
    *,
    name: str | None = None,
    rating: str | None = None,
) -> dict[str, object]:
    """Declare one explicitly placed base-tree development node."""
    spec = {
        "id": node_id,
        "kind": kind,
        "identifier": identifier,
        "lane": lane,
        "position": position,
        "prerequisites": prerequisites,
    }
    if name is not None:
        spec["name"] = name
    if rating is not None:
        spec["rating"] = rating
    return spec


